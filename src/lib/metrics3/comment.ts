/**
 * 일자별 진단 코멘트 타입.
 *
 * 그날 응대·결제 실적 축으로 병목을 짚는다(유입 코호트 축이 아니다).
 * 유입 코호트로 보면 당일 유입은 아직 성숙하지 않아 전환율이 늘 0%대로 나온다.
 *
 * 메모 원문은 코멘트를 만들 때만 읽고 저장하지 않는다 — 여기 남는 건 요약 문장뿐이다.
 */

/** 코멘트 1줄. 근거 수치를 2~3개만 붙인다 */
export interface CommentLine {
  /** 병목 축 */
  축: '사람' | '유입채널' | '재컨택' | '실패사유' | '응대속도' | '결제리드타임';
  /** 한 줄 진단 */
  본문: string;
  /** 근거 수치 (2~3개). 화면에 칩으로 붙는다 */
  근거: string[];
}

/**
 * 그날 결제된 주문 1건의 출처 추적.
 *
 * 진단 화면의 다른 표는 유입일 기준이라 그날 결제 5건이 유입일별로 흩어진다.
 * 여기는 반대로 **결제일**로 묶어 그날 결제 전부를 한자리에서 본다.
 */
export interface PaidTrace {
  /** 엑셀 주문유입채널 */
  채널: string;
  /** 리드가 붙은 테이블. 리드가 없으면 미매칭 */
  테이블: '인바운드' | 'SKB' | '미매칭';
  /** 리드 유입일. 미매칭이면 null */
  유입일: string | null;
  /** 유입 → 결제 소요일. 유입일을 모르면 null */
  소요일: number | null;
}

/** 그날 결제 전수 추적 묶음 */
export interface PaidTracking {
  /** 그날 유효 결제 주문 수 (취소·수동제외 뺀 것) */
  주문: number;
  /** 리드가 붙은 건 */
  매칭: number;
  /** 리드가 없어 유입일을 모르는 건 */
  미매칭: number;
  /** 당일 유입 → 당일 결제 */
  당일결제: number;
  /** 소요일 중앙값 (유입일을 아는 건만) */
  소요일_중앙: number | null;
  /** 소요일 최대 (유입일을 아는 건만) */
  소요일_최대: number | null;
  /** 채널별 건수 */
  채널별: { 채널: string; 건수: number }[];
  /** 개별 추적 — 소요일 내림차순 */
  건: PaidTrace[];
}

/** 하루치 코멘트 */
export interface DailyComment {
  날짜: string;
  테이블: '인바운드' | 'skb';
  /**
   * 그날 실적 요약 — 코멘트 상단 고정.
   *
   * `결제`는 그날 응대(메모 작성)까지 된 건만 센다. 대시보드의 그날 결제수(`결제_전체`)는
   * 응대 여부와 무관하게 그날 결제된 전부라 항상 이보다 크거나 같다. 두 값을 같이 남겨
   * 화면에서 차이를 설명할 수 있게 한다.
   */
  실적: {
    응대: number;
    결제: number;
    결제_전체: number;
    실패: number;
    부재중: number;
  };
  라인: CommentLine[];
  /** 그날 결제 전수 추적. 결제대조 기준일이 다르면 null */
  결제추적: PaidTracking | null;
  meta: {
    updatedAt: string;
    /** 메모를 읽은 건수. 원문은 저장하지 않는다 */
    메모검토: number;
  };
}
