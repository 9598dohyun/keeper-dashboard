/**
 * 재컨택 판정 — 접촉이력 스냅샷
 *
 * 왜 스냅샷이 필요한가:
 *   에어테이블 `메모수정시각`은 덮어쓰기 필드다. 한 리드를 8/28에 접촉하고 9/1에 다시
 *   접촉하면 필드에는 9/1만 남고 8/28은 사라진다. 즉 조회 시점의 에어테이블만으로는
 *   "이 리드가 과거에 접촉된 적이 있는지"를 알 수 없다.
 *   그래서 실행마다 `리드ID → 마지막 접촉일`을 파일로 누적해 두고, 다음 실행에서
 *   그 값과 비교해 재컨택을 판정한다.
 *
 * 판정 기준 (2026-09-01 확정):
 *   - 이력에 없던 리드가 처음 접촉일을 가지면        → 신규
 *   - 이력의 마지막 접촉일과 **날짜가 다르면**        → 재컨택
 *   - 같은 날 메모를 여러 번 수정한 건               → 신규/재컨택 어느 쪽도 아님(중복 계상 안 함).
 *     한 번의 응대 중 메모를 덧붙인 경우와 구분할 수 없어서다.
 *
 * 한계: 이력이 쌓이기 시작한 날 이전은 소급 계산할 수 없다(결제원장과 같은 성질).
 *   이력에 없는 리드는 그날이 첫 접촉인지 예전 접촉의 재방문인지 알 수 없으므로 신규로 센다.
 */

/** 리드ID → 마지막으로 관측된 접촉일(YYYY-MM-DD, KST) */
export type ContactHistory = Record<string, string>;

export interface RecontactSplit {
  /** 그날 접촉된 건 중 이력상 처음 접촉된 건 */
  신규: number;
  /** 그날 접촉된 건 중 이전에 다른 날 접촉 기록이 있던 건 */
  재컨택: number;
  /**
   * 재컨택 / (신규 + 재컨택) × 100.
   * 신규·재컨택은 둘 다 '그날 접촉된 건'이라 같은 모집단이다 — 비율로 성립한다.
   * (응대÷결제와 달리 100%를 넘을 수 없다.)
   */
  재컨택률_pct: number;
  /** 이력이 비어 있어 전부 신규로 잡힌 상태인지. true면 재컨택 0이 정상 */
  이력없음: boolean;
}

/**
 * 그날 접촉건을 신규/재컨택으로 분해한다.
 *
 * @param 접촉ID_일자 그날 접촉된 리드의 [리드ID, 접촉일] 목록
 * @param 이력 이전 실행까지 누적된 리드ID → 마지막 접촉일
 */
export function splitRecontact(
  접촉ID_일자: [string, string][],
  이력: ContactHistory
): RecontactSplit {
  const 이력없음 = Object.keys(이력).length === 0;
  let 신규 = 0;
  let 재컨택 = 0;

  for (const [id, 접촉일] of 접촉ID_일자) {
    const 이전 = 이력[id];
    if (!이전) {
      신규++;
    } else if (이전 !== 접촉일) {
      // 날짜가 바뀐 접촉만 재컨택. 같은 날 재수정은 어느 쪽으로도 세지 않는다.
      재컨택++;
    }
  }

  const 합 = 신규 + 재컨택;
  return {
    신규,
    재컨택,
    재컨택률_pct: 합 > 0 ? Math.round((재컨택 / 합) * 1000) / 10 : 0,
    이력없음,
  };
}

/**
 * 이력을 갱신한다. 그날 접촉된 리드의 접촉일로 덮어쓴다.
 *
 * 과거 날짜로 되돌리지 않는다 — 실행 순서가 뒤바뀌어도(어제 파일을 오늘 다시 돌리는 등)
 * 이력이 후퇴하면 이미 센 재컨택이 다시 신규로 잡힌다.
 */
export function updateHistory(
  이력: ContactHistory,
  접촉ID_일자: [string, string][]
): ContactHistory {
  const next: ContactHistory = { ...이력 };
  for (const [id, 접촉일] of 접촉ID_일자) {
    const 이전 = next[id];
    if (!이전 || 접촉일 > 이전) next[id] = 접촉일;
  }
  return next;
}
