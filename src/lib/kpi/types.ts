/**
 * 월 KPI 목표 대비 달성 추적.
 *
 * 목표는 **영업일에만** 배분한다(주말·법정공휴일 제외). 주말 결제가 평일의 10분의 1
 * 수준이라 균등 배분하면 주말은 구조적 미달, 평일은 과달성으로 잡힌다.
 * (실측 8/26~9/2: 평일 24~43건 / 토 3건 · 일 1건)
 */

/** 하루치 KPI 상태 */
export interface KpiDay {
  날짜: string;
  /** 요일 0=일 … 6=토 */
  요일: number;
  /** 영업일인지 (주말·공휴일이 아님) */
  영업일: boolean;
  /** 공휴일 이름. 공휴일이 아니면 null */
  공휴일: string | null;
  /** 이 날 배분된 목표. 영업일이 아니면 0 */
  목표: number;
  /**
   * 실제 결제 건수 (인바운드 + SKB, 엑셀 원장 기준).
   * 아직 데이터가 없는 미래 날짜는 null.
   */
  실적: number | null;
  /** 실적 - 목표. 실적이 null이면 null */
  차이: number | null;
  /** 그날까지 누적 목표 (영업일 기준) */
  누적목표: number;
  /** 그날까지 누적 실적. 실적이 없는 날부터는 null */
  누적실적: number | null;
}

/** 월 KPI 요약 */
export interface KpiMonth {
  /** YYYY-MM */
  월: string;
  /** 월 목표 (사용자 입력) */
  목표: number;
  /** 영업일 수 (주말·공휴일 제외) */
  영업일수: number;
  /** 영업일 하루 목표 = 목표 / 영업일수 */
  일목표: number;
  /** 집계 기준일 (이 날짜까지 실적이 있다고 본다) */
  기준일: string;
  /** 기준일까지 누적 실적 */
  누적실적: number;
  /** 기준일까지 누적 목표 */
  누적목표: number;
  /** 누적실적 - 누적목표. 양수면 초과 달성 */
  격차: number;
  /** 목표까지 남은 건수 = 목표 - 누적실적 */
  잔여: number;
  /** 기준일 다음날부터 월말까지 남은 영업일 수 */
  잔여영업일: number;
  /**
   * 남은 영업일 하루에 해야 하는 건수 = 잔여 / 잔여영업일.
   * 잔여영업일이 0이면 null (월이 끝났거나 남은 영업일이 없음).
   */
  필요일평균: number | null;
  /** 달성률 = 누적실적 / 목표 × 100 */
  달성률_pct: number;
  /** 현재 속도로 월말까지 갔을 때 예상 착지 = 일평균 × 영업일수 */
  예상착지: number;
  일별: KpiDay[];
}
